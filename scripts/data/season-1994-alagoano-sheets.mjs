/** Absolute minute: 1ºT = m; 2ºT = 45+m; prorrogação 1/2 = 90+m / 105+m */
export function absMin(half, m, etHalf = 0) {
  if (m == null) return 0;
  if (etHalf === 1) return 90 + m;
  if (etHalf === 2) return 105 + m;
  return half === 2 ? 45 + m : m;
}

